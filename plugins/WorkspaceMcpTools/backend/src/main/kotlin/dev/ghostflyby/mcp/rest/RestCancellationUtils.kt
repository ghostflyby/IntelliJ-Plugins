package dev.ghostflyby.mcp.rest

import kotlinx.coroutines.CancellationException

// runCatching swallows CancellationException and breaks coroutine cancellation
// in suspend route handlers.
internal inline fun <T> runCatchingRethrowingCancellation(block: () -> T): Result<T> =
    try {
        Result.success(block())
    } catch (e: CancellationException) {
        throw e
    } catch (t: Throwable) {
        Result.failure(t)
    }
